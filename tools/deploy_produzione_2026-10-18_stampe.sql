		BEGIN
			SET @returnValue = -1;
			SET @returnMessage = 'Selezionare un file di dimensioni inferiori a 200 KB';
			GOTO BRANCH_END;
		END

		BEGIN TRANSACTION;
			UPDATE dbo.tblSediReport WITH (UPDLOCK, HOLDLOCK)
			SET Logo = @Logo
			WHERE Id = @idAzienda;

