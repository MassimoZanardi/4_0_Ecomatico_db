				INSERT dbo.tblSediReport (Id, IdLayout, Intestazione, Piepagina, IntestazioneColore, IntestazioneFontSize, IntestazioneAllineamento, PiepaginaColore, PiepaginaFontSize, PiepaginaAllineamento, Logo)
